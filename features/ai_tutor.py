class AiTutor:
    def __init__(self, brain=None):
        self.brain = brain

    def lesson(self, text: str) -> str:
        low = text.lower()
        import re
        m = re.search(r"(?:урок|тему|глава)\s*(\d+)?", low)
        if m and m.group(1):
            num = int(m.group(1))
            les = next((l for l in LESSONS if l["id"] == num), None)
            if not les:
                return f"Урока {num} нет, сэр. Программа: {len(LESSONS)} уроков."
            return (f"Урок {les['id']}: {les['title']}. {les['body']} "
                    f"Скажите «следующий урок», чтобы продолжить.")
        if any(w in low for w in ("следующ", "дальше", "продолж")):
            # берём первый ещё не пройденный
            from core.config import data_file
            import json
            prog = data_file("tutor_progress.json")
            done = []
            if prog.exists():
                done = json.load(open(prog, encoding="utf-8"))
            nxt = next((l for l in LESSONS if l["id"] not in done), None)
            if not nxt:
                return ("Программа пройдена полностью, сэр! Дальше — только практика "
                        "и свои проекты. Могу углубиться в любую тему по запросу.")
            done.append(nxt["id"])
            json.dump(done, open(prog, "w", encoding="utf-8"))
            return f"Урок {nxt['id']}: {nxt['title']}. {nxt['body']}"
        if "программа" in low or "список" in low:
            titles = "; ".join(f"{l['id']}. {l['title']}" for l in LESSONS)
            return f"Курс «Нейросети с нуля»: {titles}. Скажите «следующий урок»."
        # свободный вопрос → через мозг
        if self.brain:
            q = text.split("про")[-1].strip()
            answer = self.brain.ask(
                f"Объясни как ментор-практик, кратко и по делу, с примером кода если уместно: {q}"
            )
            if answer:
                return answer
        return ("Формат: «урок по нейросетям программа» — список, "
                "«следующий урок» — продолжить, или спросите «объясни про RAG».")
